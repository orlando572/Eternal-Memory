-- TSK-10. Only server callers may quote or create orders.
create table public.checkout_locations (
  ubigeo text primary key check (ubigeo ~ '^[0-9]{6}$'),
  department text not null,
  province text not null,
  district text not null,
  is_covered boolean not null default true
);
alter table public.checkout_locations enable row level security;
revoke all on public.checkout_locations from public, anon, authenticated;
grant select on public.checkout_locations to service_role;

create table public.checkout_customization_rules (
  mode text primary key,
  category_slug text not null references public.categories(slug),
  unit_surcharge_pen numeric(12,2) not null check (unit_surcharge_pen >= 0),
  max_characters integer not null check (max_characters between 1 and 300),
  is_active boolean not null default true
);
alter table public.checkout_customization_rules enable row level security;
revoke all on public.checkout_customization_rules from public, anon, authenticated;
grant select on public.checkout_customization_rules to service_role;
insert into public.checkout_customization_rules (mode, category_slug, unit_surcharge_pen, max_characters)
  select 'urn_name', slug, 25, 80 from public.categories where slug = 'urnas';

create table public.checkout_quotes (
  id uuid primary key default gen_random_uuid(),
  customer_id uuid not null references auth.users(id) on delete cascade,
  payload jsonb not null,
  summary jsonb not null,
  expires_at timestamptz not null default (now() + interval '5 minutes'),
  created_at timestamptz not null default now()
);
alter table public.checkout_quotes enable row level security;
revoke all on public.checkout_quotes from public, anon, authenticated;
grant select, insert, delete on public.checkout_quotes to service_role;
create index checkout_quotes_customer_idx on public.checkout_quotes(customer_id);
create index checkout_quotes_expiry_idx on public.checkout_quotes(expires_at);

