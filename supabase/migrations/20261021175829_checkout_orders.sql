create function app_private.calculate_checkout(p_payload jsonb) returns jsonb
language plpgsql security invoker set search_path = '' as $$
declare
  v_location public.checkout_locations%rowtype;
  v_zone text;
  v_delivery numeric(12,2);
  v_line jsonb;
  v_row record;
  v_rule public.checkout_customization_rules%rowtype;
  v_quantity integer;
  v_fee numeric(12,2);
  v_base numeric(12,2) := 0;
  v_custom numeric(12,2) := 0;
  v_lines jsonb := '[]'::jsonb;
begin
  if p_payload is null or jsonb_typeof(p_payload) <> 'object'
    or jsonb_typeof(p_payload->'lines') is distinct from 'array' then
    raise exception 'INVALID_INPUT';
  end if;
  if jsonb_array_length(p_payload->'lines') not between 1 and 50 then raise exception 'INVALID_CART'; end if;
  if coalesce(length(btrim(p_payload->>'contactName')),0) not between 2 and 120
    or coalesce(length(p_payload->>'contactEmail'),0) not between 3 and 254
    or (p_payload->>'contactEmail') !~ '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$'
    or coalesce(length(p_payload->>'contactPhone'),0) not between 7 and 20
    or (p_payload->>'contactPhone') !~ '^\+?[0-9 ()-]{7,20}$'
    or coalesce(length(regexp_replace(p_payload->>'contactPhone','[^0-9]','','g')),0) < 7
    or coalesce(length(btrim(p_payload->>'addressLine')),0) not between 5 and 240
    or length(coalesce(p_payload->>'addressDetail','')) > 300 then raise exception 'INVALID_INPUT'; end if;
  select * into v_location from public.checkout_locations where ubigeo = p_payload->>'ubigeo' for share;
  if not found then raise exception 'INVALID_LOCATION'; end if;
  if not v_location.is_covered then raise exception 'DELIVERY_UNAVAILABLE'; end if;
  v_zone := case when left(v_location.ubigeo,4) = '0401' then 'arequipa_province' else 'rest_of_peru' end;
  select price_pen into v_delivery from public.delivery_rates where zone = v_zone and is_active and price_pen is not null for share;
  if not found then raise exception 'DELIVERY_NOT_CONFIGURED'; end if;

  -- Validate EACH original quantity before aggregation (no negative compensation).
  for v_line in select value from jsonb_array_elements(p_payload->'lines') loop
    if jsonb_typeof(v_line) <> 'object' or jsonb_typeof(v_line->'quantity') is distinct from 'number'
      or (v_line->>'quantity') !~ '^[0-9]+$' or length(v_line->>'quantity') > 2
      or (v_line->>'quantity')::integer not between 1 and 50
      or coalesce(length(btrim(v_line->>'key')),0) not between 1 and 200
      or coalesce(v_line->>'variantId','') !~* '^[0-9a-f]{8}(-[0-9a-f]{4}){3}-[0-9a-f]{12}$'
      or coalesce(v_line->>'productId','') !~* '^[0-9a-f]{8}(-[0-9a-f]{4}){3}-[0-9a-f]{12}$' then
      raise exception 'INVALID_CART';
    end if;
  end loop;
  if (select count(distinct value->>'key') from jsonb_array_elements(p_payload->'lines')) <> jsonb_array_length(p_payload->'lines') then raise exception 'INVALID_CART'; end if;

  -- Stable locks also protect against concurrent catalog/stock changes.
  for v_row in
    select v.id from public.product_variants v
      where v.id in (select (value->>'variantId')::uuid from jsonb_array_elements(p_payload->'lines'))
      order by v.id for update
  loop
    select sum((value->>'quantity')::integer) into v_quantity from jsonb_array_elements(p_payload->'lines') where (value->>'variantId')::uuid = v_row.id;
    if v_quantity > 50 then raise exception 'INVALID_CART'; end if;
    if not exists (select 1 from public.product_variants where id = v_row.id and stock_on_hand - stock_reserved >= v_quantity) then raise exception 'INSUFFICIENT_STOCK'; end if;
  end loop;

  for v_line in select value from jsonb_array_elements(p_payload->'lines') order by value->>'key' loop
    select v.*, p.name product_name, p.status, c.slug category_slug, c.is_active category_active into v_row
      from public.product_variants v join public.products p on p.id = v.product_id join public.categories c on c.id = p.category_id
      where v.id = (v_line->>'variantId')::uuid and p.id = (v_line->>'productId')::uuid for share of p,c;
    if not found or not v_row.is_active or v_row.status <> 'published' or not v_row.category_active then raise exception 'VARIANT_UNAVAILABLE'; end if;
    v_quantity := (v_line->>'quantity')::integer;
    v_fee := 0;
    if v_line->'customization' is not null and v_line->'customization' <> 'null'::jsonb then
      select * into v_rule from public.checkout_customization_rules where mode = v_line->'customization'->>'mode'
        and category_slug = v_row.category_slug and is_active for share;
      if not found or jsonb_typeof(v_line->'customization'->'text') is distinct from 'string'
        or length(btrim(v_line->'customization'->>'text')) not between 1 and v_rule.max_characters
        or (v_line->'customization'->>'text') ~ '[[:cntrl:]<>]' then raise exception 'INVALID_CUSTOMIZATION'; end if;
      v_fee := v_rule.unit_surcharge_pen;
    end if;
    v_base := v_base + v_row.price_pen * v_quantity;
    v_custom := v_custom + v_fee * v_quantity;
    v_lines := v_lines || jsonb_build_array(jsonb_build_object(
      'key',v_line->>'key', 'productId',v_row.product_id, 'variantId',v_row.id,
      'quantity',v_quantity, 'customization',v_line->'customization',
      'productName',v_row.product_name, 'variantName',v_row.name,
      'baseUnitPricePen',v_row.price_pen, 'customizationUnitPen',v_fee,
      'unitPricePen',v_row.price_pen+v_fee, 'lineTotalPen',(v_row.price_pen+v_fee)*v_quantity));
  end loop;
  return jsonb_build_object('lines',v_lines, 'location',jsonb_build_object('ubigeo',v_location.ubigeo,
    'department',v_location.department,'province',v_location.province,'district',v_location.district),
    'deliveryZone',v_zone, 'baseSubtotalPen',v_base, 'customizationPen',v_custom,
    'subtotalPen',v_base+v_custom, 'deliveryPen',v_delivery, 'totalPen',v_base+v_custom+v_delivery);
end;
$$;
revoke all on function app_private.calculate_checkout(jsonb) from public, anon, authenticated;
grant usage on schema app_private to service_role;
grant execute on function app_private.calculate_checkout(jsonb) to service_role;

create function public.quote_checkout(p_customer_id uuid, p_payload jsonb) returns jsonb
language plpgsql security invoker set search_path = '' as $$
declare v_summary jsonb; v_quote public.checkout_quotes%rowtype;
begin
  if p_customer_id is null then raise exception 'INVALID_INPUT'; end if;
  -- Serialize per customer and bound quote storage; no inventory reservation here.
  perform pg_advisory_xact_lock(hashtextextended(p_customer_id::text, 10));
  delete from public.checkout_quotes where customer_id=p_customer_id and expires_at < now();
  if (select count(*) from public.checkout_quotes where customer_id=p_customer_id) >= 30 then raise exception 'TOO_MANY_QUOTES'; end if;
  v_summary := app_private.calculate_checkout(p_payload);
  insert into public.checkout_quotes(customer_id,payload,summary) values(p_customer_id,p_payload,v_summary) returning * into v_quote;
  return jsonb_build_object('quoteId',v_quote.id, 'expiresAt',v_quote.expires_at, 'summary',v_summary);
end;
$$;
revoke all on function public.quote_checkout(uuid,jsonb) from public, anon, authenticated;
grant execute on function public.quote_checkout(uuid,jsonb) to service_role;

create function public.create_checkout_order(p_customer_id uuid, p_quote_id uuid, p_idempotency_key uuid) returns uuid
language plpgsql security invoker set search_path = '' as $$
declare v_quote public.checkout_quotes%rowtype; v_existing public.orders%rowtype;
  v_summary jsonb; v_id uuid; v_line jsonb; v_item record;
begin
  if p_customer_id is null or p_quote_id is null or p_idempotency_key is null then raise exception 'INVALID_INPUT'; end if;
  perform pg_advisory_xact_lock(hashtextextended(p_customer_id::text || ':' || p_idempotency_key::text, 11));
  select * into v_existing from public.orders where customer_id=p_customer_id and idempotency_key=p_idempotency_key;
  if found then
    if v_existing.checkout_quote_id <> p_quote_id then raise exception 'IDEMPOTENCY_CONFLICT'; end if;
    return v_existing.id;
  end if;
  select * into v_quote from public.checkout_quotes where id=p_quote_id and customer_id=p_customer_id for share;
  if not found or v_quote.expires_at <= now() then raise exception 'QUOTE_EXPIRED'; end if;
  v_summary := app_private.calculate_checkout(v_quote.payload);
  if v_summary <> v_quote.summary then raise exception 'QUOTE_CHANGED'; end if;
  insert into public.orders(customer_id,idempotency_key,checkout_quote_id,request_hash,delivery_ubigeo,
    contact_name,contact_email,contact_phone,address_line,address_detail,department,province,district,
    delivery_zone,subtotal_pen,delivery_pen,reservation_expires_at)
  values(p_customer_id,p_idempotency_key,p_quote_id,encode(extensions.digest(v_quote.payload::text,'sha256'),'hex'),
    v_quote.payload->>'ubigeo', v_quote.payload->>'contactName',v_quote.payload->>'contactEmail',v_quote.payload->>'contactPhone',
    v_quote.payload->>'addressLine',nullif(v_quote.payload->>'addressDetail',''), v_summary->'location'->>'department',
    v_summary->'location'->>'province',v_summary->'location'->>'district',v_summary->>'deliveryZone',
    (v_summary->>'subtotalPen')::numeric,(v_summary->>'deliveryPen')::numeric,now()+interval '30 minutes') returning id into v_id;
  for v_line in select value from jsonb_array_elements(v_summary->'lines') loop
    insert into public.order_items(order_id,line_key,variant_id,product_name,variant_name,quantity,unit_price_pen,
      base_unit_price_pen,customization_unit_pen,customization)
    values(v_id,v_line->>'key',(v_line->>'variantId')::uuid,v_line->>'productName',v_line->>'variantName',
      (v_line->>'quantity')::integer,(v_line->>'unitPricePen')::numeric,(v_line->>'baseUnitPricePen')::numeric,
      (v_line->>'customizationUnitPen')::numeric,nullif(v_line->'customization','null'::jsonb));
  end loop;
  for v_item in select variant_id,sum(quantity)::integer quantity from public.order_items where order_id=v_id group by variant_id order by variant_id loop
    update public.product_variants set stock_reserved=stock_reserved+v_item.quantity where id=v_item.variant_id;
  end loop;
  insert into public.order_status_history(order_id,to_status,actor_id) values(v_id,'pending_payment',p_customer_id);
  return v_id;
end;
$$;
revoke all on function public.create_checkout_order(uuid,uuid,uuid) from public, anon, authenticated;
grant execute on function public.create_checkout_order(uuid,uuid,uuid) to service_role;

